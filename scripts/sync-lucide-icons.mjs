#!/usr/bin/env node
/**
 * Sync Lucide static SVGs into Wall-E's Native icon registry.
 *
 * Source: lucide-static (https://lucide.dev/guide/static/)
 * Native wiring: canvas.svg_icon.parseComptime + registerAppIcons + markup `app:<name>`.
 *
 * Usage:
 *   node scripts/sync-lucide-icons.mjs
 *
 * Edit ICON_NAMES below (or pass names as CLI args) then re-run.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const lucideIconsDir = path.join(root, "node_modules", "lucide-static", "icons");
const outAssets = path.join(root, "assets", "icons");
const outZig = path.join(root, "src", "theme", "lucide_icons.zig");

/** Curated Wall-E set — agent shell + current UI. Add Lucide kebab-case names here. */
const DEFAULT_ICONS = [
  // Titlebar / theme
  "terminal",
  "sun",
  "moon",
  "monitor",
  // Sessions / navigation
  "folder",
  "folder-open",
  "panel-left",
  "message-square",
  "bot",
  "sparkles",
  // Conversation / compose
  "arrow-up",
  "send",
  "plus",
  "paperclip",
  "mic",
  // Review / files
  "file-text",
  "file-code",
  "code",
  "git-branch",
  "git-pull-request",
  "diff",
  // Status / actions
  "check",
  "check-circle",
  "x",
  "x-circle",
  "alert-circle",
  "info",
  "loader-circle",
  "refresh-cw",
  "copy",
  "trash-2",
  "settings",
  "search",
  "ellipsis",
  "chevron-right",
  "chevron-down",
  "external-link",
  "play",
  "square",
];

function cleanSvg(raw) {
  return raw
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+class="[^"]*"/g, "")
    .replace(/\n+/g, "\n")
    .trim();
}

function zigRawString(svg) {
  // Zig multiline string: each line prefixed with \\
  const lines = svg.split("\n");
  return lines.map((line) => `    \\\\${line}`).join("\n");
}

function zigIdent(name) {
  // folder-open → folder_open
  const id = name.replace(/-/g, "_");
  if (/^[0-9]/.test(id)) return `icon_${id}`;
  return id;
}

function main() {
  if (!fs.existsSync(lucideIconsDir)) {
    console.error(
      "error: lucide-static not installed — run `npm install lucide-static`",
    );
    process.exit(1);
  }

  const names = process.argv.slice(2).length > 0 ? process.argv.slice(2) : DEFAULT_ICONS;
  const unique = [...new Set(names)].sort();
  fs.mkdirSync(outAssets, { recursive: true });

  const entries = [];
  for (const name of unique) {
    const src = path.join(lucideIconsDir, `${name}.svg`);
    if (!fs.existsSync(src)) {
      console.error(`error: missing Lucide icon "${name}" (${src})`);
      process.exit(1);
    }
    const cleaned = cleanSvg(fs.readFileSync(src, "utf8"));
    fs.writeFileSync(path.join(outAssets, `${name}.svg`), cleaned + "\n");
    entries.push({ name, ident: zigIdent(name), svg: cleaned });
  }

  const body = entries
    .map(
      (e) =>
        `const ${e.ident} = canvas.svg_icon.parseComptime(\n${zigRawString(e.svg)}\n);`,
    )
    .join("\n\n");

  const table = entries
    .map((e) => `    .{ .name = "${e.name}", .icon = &${e.ident} },`)
    .join("\n");

  const zig = `//! Lucide static icon registry for Native SDK.
//!
//! Generated by \`scripts/sync-lucide-icons.mjs\` from \`lucide-static\`.
//! Do not hand-edit the parsed SVG bodies — change ICON_NAMES in the
//! script and re-run. Markup references: \`app:<name>\` (e.g. app:folder).
//!
//! @see https://lucide.dev/guide/static/
//! @see https://lucide.dev/icons/

const native_sdk = @import("native_sdk");
const canvas = native_sdk.canvas;

${body}

/// Same table handed to \`canvas.icons.registerAppIcons\` and exposed as
/// \`pub const app_icons\` on the app root for \`native check\`.
pub const app_icons = [_]canvas.icons.Entry{
${table}
};

pub fn register() void {
    canvas.icons.registerAppIcons(&app_icons);
}
`;

  fs.writeFileSync(outZig, zig);
  console.log(
    `synced ${entries.length} Lucide icons → assets/icons/ + src/theme/lucide_icons.zig`,
  );
  console.log(entries.map((e) => e.name).join(", "));
}

main();
